export function buildPersonaEntries() {
  const entries = [];
  let order = 50;
  for (const [key, stages] of Object.entries(PERSONAS)) {
    stages.forEach((content, i) => {
      entries.push({
        name: personaEntryName(key, STAGES[i]),
        enabled: i === 0, // 初始全员抵触阶段
        constant: true, position: 0, depth: 1, order,
        content,
      });
    });
    order += 1;
  }
  return entries;
}
